/** 价格解析：从任意价格文本推导数值 / 币种 / 是否免费 */
function derivePrice(text) {
  var s = String(text == null ? '' : text).trim();
  if (!s) return { value: null, currency: '', isFree: null };
  if (/無料|无料|免费|free/i.test(s)) return { value: 0, currency: '', isFree: true };
  var cur = '';
  if (/[¥￥]|JPY|円/i.test(s)) cur = 'JPY';
  else if (/[$]|USD/i.test(s)) cur = 'USD';
  else if (/[€]|EUR/i.test(s)) cur = 'EUR';
  else if (/CNY|RMB|元/i.test(s)) cur = 'CNY';
  var m = s.replace(/,/g, '').match(/(\d+(?:\.\d+)?)/);
  var v = m ? parseFloat(m[1]) : null;
  return { value: v, currency: cur, isFree: v === null ? null : v === 0 };
}

